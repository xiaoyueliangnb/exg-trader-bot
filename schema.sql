CREATE DATABASE IF NOT EXISTS jifen
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_general_ci;

USE jifen;

CREATE TABLE IF NOT EXISTS avg_cache (
  cache_date DATE NOT NULL,
  point_avg DOUBLE NOT NULL,
  coin_avg DOUBLE NOT NULL,
  n_point INT NOT NULL DEFAULT 5,
  n_coin INT NOT NULL DEFAULT 5,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (cache_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS daily_profit (
  profit_date DATE NOT NULL,
  n_coin INT NOT NULL DEFAULT 0,
  n_pt INT NOT NULL DEFAULT 0,
  n_pair INT NOT NULL DEFAULT 0,
  n_redeem INT NOT NULL DEFAULT 0,
  coin_n INT NOT NULL DEFAULT 0,
  coin_pts INT NOT NULL DEFAULT 0,
  fee_c INT NOT NULL DEFAULT 0,
  pt_n INT NOT NULL DEFAULT 0,
  pt_pts INT NOT NULL DEFAULT 0,
  fee_p INT NOT NULL DEFAULT 0,
  redeem_fee INT NOT NULL DEFAULT 0,
  net_coin INT NOT NULL DEFAULT 0,
  profit INT NOT NULL DEFAULT 0,
  n_listed INT NOT NULL DEFAULT 0,
  settled_on DATE NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (profit_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS profit_meta (
  id TINYINT NOT NULL,
  as_of DATE NULL,
  yesterday DATE NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS day_detail (
  detail_date DATE NOT NULL,
  listed_json LONGTEXT NOT NULL,
  pairs_json LONGTEXT NOT NULL,
  redeem_json LONGTEXT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (detail_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 每轮扫描的分档盘口快照（全部数量档，不只 10 币）
CREATE TABLE IF NOT EXISTS market_snapshot (
  id BIGINT NOT NULL AUTO_INCREMENT,
  ts DATETIME NOT NULL,
  payload_json LONGTEXT NOT NULL,
  PRIMARY KEY (id),
  KEY idx_ts (ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 每次提交上架时的价格与盘口上下文
CREATE TABLE IF NOT EXISTS listing_submit (
  id BIGINT NOT NULL AUTO_INCREMENT,
  ts DATETIME NOT NULL,
  kind VARCHAR(16) NOT NULL,
  coins INT NOT NULL,
  points INT NOT NULL,
  rate INT NOT NULL,
  book_top DOUBLE NULL,
  book_second DOUBLE NULL,
  avg5 DOUBLE NULL,
  profit INT NOT NULL DEFAULT 0,
  money INT NULL,
  coin INT NULL,
  PRIMARY KEY (id),
  KEY idx_ts (ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 自己每张单的生命周期：首次看到在售 → 成交 / 赎回
CREATE TABLE IF NOT EXISTS listing_track (
  listing_id BIGINT NOT NULL,
  kind VARCHAR(16) NOT NULL,
  coins INT NOT NULL,
  points INT NOT NULL,
  rate DOUBLE NOT NULL,
  first_seen DATETIME NULL,
  closed_at DATETIME NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (listing_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
